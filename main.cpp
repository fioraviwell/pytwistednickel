#include <string>
#include <vector>

void integer_power() {
    int base = 2, exp = 8;
    int power = 1;
    for (int i = 0; i < exp; ++i) power *= base;
    (void)power;
}

void count_vowels() {
    std::string text = "prism bridge";
    int vowels = 0;
    for (std::size_t i = 0; i < text.size(); ++i) {
        char ch = text[i];
        if (ch == 'a' || ch == 'e' || ch == 'i' || ch == 'o' || ch == 'u') vowels += 1;
    }
    (void)vowels;
}

void sum_evens() {
    int values[5] = {2, 4, 6, 8, 10};
    int acc = 0;
    for (int i = 0; i < 5; ++i) acc += values[i];
    (void)acc;
}

void count_multiples() {
    int count = 0;
    for (int i = 1; i <= 100; ++i) {
        if (i % 7 == 0) count += 1;
    }
    (void)count;
}

extern "C" int mellow_fjord();
extern "C" void golden_prism();
extern "C" void swift_vale();
extern "C" void misty_fjord();

int main() {
    integer_power();
    count_vowels();
    sum_evens();
    count_multiples();
    golden_prism();
    swift_vale();
    misty_fjord();
    return mellow_fjord();
}
